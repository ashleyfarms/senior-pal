export function getDiscount(id: string): Discount | undefined {
  return DISCOUNTS.find((d) => d.id === id);
}

/** National deals + city-scoped deals for the given city. */
export function discountsForCity(cityId: string): Discount[] {
  return DISCOUNTS.filter(
    (d) => d.scope === 'national' || (d.scope === 'city' && d.cityId === cityId),
  );
}

export function categoryLabel(id: Discount['category']): string {
  const map: Record<Discount['category'], string> = {
    pharmacy: 'Pharmacy',
    retail: 'Retail',
    dining: 'Dining',
    grocery: 'Grocery',
    entertainment: 'Entertainment',
    travel: 'Travel',
    services: 'Services',
    transit: 'Transit',
    attractions: 'Attractions',
  };
  return map[id];
}

/** Human-readable eligibility line for cards — age and/or membership always shown. */
export function eligibilityLabel(d: Discount): string {
  const parts: string[] = [];
  if (d.minAge != null) parts.push(`${d.minAge}+`);
  if (d.membership) parts.push(d.membership);
  if (parts.length === 0) return 'Eligibility varies — verify';
  return parts.join(' · ');
}

